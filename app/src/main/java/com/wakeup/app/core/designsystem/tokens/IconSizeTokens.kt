package com.wakeup.app.core.designsystem.tokens

import androidx.compose.ui.unit.dp

/**
 * Standard icon sizes for visual consistency.
 */
object IconSizeTokens {
    /** 16dp - Extra small, inline indicators, badges */
    val xs = 16.dp
    
    /** 20dp - Small, list items, compact UI */
    val sm = 20.dp
    
    /** 24dp - Medium, standard UI elements (default) */
    val md = 24.dp
    
    /** 28dp - Medium-large, feature icons */
    val mdLg = 28.dp
    
    /** 32dp - Large, prominent icons */
    val lg = 32.dp
    
    /** 40dp - Extra large, hero icons */
    val xl = 40.dp
    
    /** 44dp - 2x Large, touch targets, nav icons */
    val xxl = 44.dp
    
    /** 48dp - 3x Large, minimum touch target */
    val touchTarget = 48.dp
    
    /** Icon container sizes */
    val containerSm = 32.dp
    val containerMd = 40.dp
    val containerLg = 48.dp
}
